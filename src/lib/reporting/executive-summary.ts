/** Pre-built "comparator pending" comparison row. Used when a KPI's
 *  budget / policy comparator is null (budget not yet posted for
 *  the period). The KPI tile renders `value: "Pending"` with a
 *  conservative "comparative not available" variance string so the
 *  board sees that the comparison is in-flight rather than zero. */
const PENDING_COMPARATOR_ROW = {
  label: "vs Budget",
  value: "Pending",
  variance: "comparative not available",
} as const;

function buildYtdRevenueCard(input: AccountingMetricInput): KpiCard {
  if (input.comparator === null) {
    return {
      key: "ytd-revenue",
      label: "YTD Revenue",
      value: formatMoneyShort(input.actual),
      context: "Total operating revenue earned through the period close.",
      comparison: { ...PENDING_COMPARATOR_ROW },
      tone: "neutral",
    };
  }
  const variancePct = (input.actual - input.comparator) / Math.abs(input.comparator);
  const sign = variancePct >= 0 ? "above" : "below";
  return {
    key: "ytd-revenue",
    label: "YTD Revenue",
    value: formatMoneyShort(input.actual),
    context: "Total operating revenue earned through the period close.",
    comparison: {
      label: "vs Budget",
      value: formatMoneyShort(input.comparator),
      variance: `${formatVariancePct(variancePct)} ${sign} plan`,
    },
    tone: toneForBudgetMetric(input.actual, input.comparator),
  };
}

