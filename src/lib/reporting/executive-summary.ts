// ---------------------------------------------------------------------------
// Consideration cascade — worst KPI tone wins
// ---------------------------------------------------------------------------

function cascadeConsideration(kpis: KpiCard[]): BoardConsideration {
  const tones = new Set(kpis.map((k) => k.tone ?? "neutral"));
  if (tones.has("red")) return "committee-review";
  if (tones.has("amber")) return "monitor";
  return "no-action";
}

