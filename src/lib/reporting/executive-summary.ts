/**
 * Reactive cover-page narrative generator.
 *
 * Composition (when full data is available, in order):
 *   1. Opening verdict — "in line with / above / below plan" based on
 *      worst KPI tone. Conservative language; no all-caps drama.
 *   2. Revenue clause — actual + variance vs budget in $ and %.
 *   3. NOI clause — same.
 *   4. Capital Income clause — same.
 *   5. Reserve Coverage clause — names the policy floor relationship.
 *   6. Largest-variance callout — names the single most favourable and
 *      (if separately material) the single most unfavourable variance.
 *   7. Pillar verdict + action line.
 *
 * Fallback branches:
 *   - All three primary comparators (revenue / NOI / capital) are
 *     `null` → emit a short fallback paragraph; do not invent
 *     verdicts.
 *   - One or two are `null` → omit those clauses and add a
 *     "comparators pending for: ..." aside so the reader sees the
 *     omission was intentional.
 *
 * Language rules (board-report tone, restrained):
 *   - Numeric variances are stated, not editorialised. "+3.7 % above
 *     plan" not "tracking favorably to plan".
 *   - "Off plan" never appears in all caps.
 *   - The word "materially" only applies when |variance| ≥ 10 %.
 *   - The opener avoids "OFF PLAN" / "FAVORABLE" / "STRONG" — uses
 *     "operating in line with plan" / "operating below plan" /
 *     "operating above plan".
 */
export function buildExecutiveSummaryHeadline(
  input: ExecutiveSummaryInput,
  kpis: KpiCard[],
): string {
  const period = input.period.periodLabel;

  // Gather variances for the three primary metrics so the headline
  // can name them individually + identify the largest favourable
  // and largest unfavourable.
  type PrimaryVariance = {
    /** Pretty label used in the headline. */
    label: string;
    /** Variance % (actual − budget) / |budget|, or null if budget missing. */
    variancePct: number | null;
    /** Variance amount in dollars, or null if budget missing. */
    varianceAmount: number | null;
    actual: number;
    comparator: number | null;
  };
  const primaries: PrimaryVariance[] = [
    {
      label: "operating revenue",
      ...computeVariance(input.ytdRevenue),
    },
    {
      label: "NOI before depreciation",
      ...computeVariance(input.ytdNoiBeforeDepreciation),
    },
    {
      label: "capital income",
      ...computeVariance(input.ytdCapitalIncome),
    },
  ];
  const availablePrimaries = primaries.filter((p) => p.variancePct !== null);
  const missingPrimaryLabels = primaries
    .filter((p) => p.variancePct === null)
    .map((p) => p.label);

  // -----------------------------------------------------------------
  // FALLBACK BRANCH — every primary comparator is null. The headline
  // does not attempt to verdict-cast; it states that the comparators
  // are pending so the reader knows the omission is intentional.
  // -----------------------------------------------------------------
  if (availablePrimaries.length === 0) {
    return (
      `${input.clubName} — ${period} cover summary not yet available. ` +
      `Budget comparators are pending for operating revenue, NOI before depreciation, and capital income. ` +
      `YTD actuals are listed in the cards above; the narrative will populate once full data flows from the accounting service.`
    );
  }

  // -----------------------------------------------------------------
  // FULL OR PARTIAL NARRATIVE
  // -----------------------------------------------------------------

  // 1. Opening verdict — based on worst KPI tone across the cards.
  //    Conservative wording; no all-caps drama.
  const tones = new Set(kpis.map((k) => k.tone ?? "neutral"));
  const anyRed = tones.has("red");
  const anyAmber = tones.has("amber");
  let opener: string;
  if (anyRed) {
    opener = `${input.clubName} is operating below plan through ${period}.`;
  } else if (anyAmber) {
    opener = `${input.clubName} is operating largely in line with plan through ${period}, with specific items to monitor.`;
  } else {
    opener = `${input.clubName} is operating in line with plan through ${period}.`;
  }

  // 2-4. Primary-metric clauses — one sentence per available metric.
  const primaryClauses: string[] = [];
  const revClause = describePrimaryVariance({
    label: "Operating revenue",
    actual: input.ytdRevenue.actual,
    comparator: input.ytdRevenue.comparator,
  });
  if (revClause) primaryClauses.push(revClause);
  const noiClause = describePrimaryVariance({
    label: "NOI before depreciation",
    actual: input.ytdNoiBeforeDepreciation.actual,
    comparator: input.ytdNoiBeforeDepreciation.comparator,
  });
  if (noiClause) primaryClauses.push(noiClause);
  const capClause = describePrimaryVariance({
    label: "Capital income",
    actual: input.ytdCapitalIncome.actual,
    comparator: input.ytdCapitalIncome.comparator,
  });
  if (capClause) primaryClauses.push(capClause);

  // Partial-data aside — only emitted when SOME primaries were
  // omitted (1 or 2 missing). The full-fallback branch above
  // handles 3-missing.
  let partialDataAside: string | null = null;
  if (missingPrimaryLabels.length > 0) {
    partialDataAside =
      `Comparators are not yet posted for: ${missingPrimaryLabels.join(", ")} — those clauses will populate when budget data flows.`;
  }

  // 5. Reserve coverage clause.
  let reserveClause: string;
  if (input.reserveCoverage.comparator === null) {
    reserveClause = `Capital reserve coverage is ${formatRatio(input.reserveCoverage.actual)}; the policy floor is not yet configured in the reporting service.`;
  } else {
    const ratio = input.reserveCoverage.actual;
    const floor = input.reserveCoverage.comparator;
    if (ratio >= floor) {
      reserveClause = `Capital reserve coverage holds at ${formatRatio(ratio)}, above the ${formatRatio(floor)} policy floor.`;
    } else if (ratio >= floor * 0.95) {
      reserveClause = `Capital reserve coverage sits at ${formatRatio(ratio)}, at the ${formatRatio(floor)} policy floor; the margin warrants monitoring.`;
    } else {
      reserveClause = `Capital reserve coverage has declined to ${formatRatio(ratio)}, below the ${formatRatio(floor)} policy floor.`;
    }
  }

  // 6. Largest-variance callout — names the most favourable and (if
  //    separately material) the most unfavourable. Restrained:
  //    "no material variances" is an acceptable callout when none
  //    exceed the 5 % material threshold.
  const callout = buildLargestVarianceCallout(availablePrimaries);

  // 7. Optional F&B subsidy clause — only when data is available.
  let fbClause: string | null = null;
  if (input.fbSubsidy) {
    const fb = input.fbSubsidy;
    const direction =
      fb.trend === "improving"
        ? "continuing a downward trend"
        : fb.trend === "worsening"
          ? "and trending upward"
          : "and holding steady";
    if (fb.actual <= fb.ceiling) {
      fbClause = `The F&B subsidy of dues is ${formatPct(fb.actual)}, below the ${formatPct(fb.ceiling)} ceiling, ${direction}.`;
    } else {
      fbClause = `The F&B subsidy of dues is ${formatPct(fb.actual)}, above the ${formatPct(fb.ceiling)} ceiling, ${direction}.`;
    }
  }

  // 8. Pillar verdict.
  function pillarVerdict(...keys: string[]): "favorable" | "monitor" | "unfavorable" {
    const pillarTones = kpis
      .filter((k) => keys.includes(k.key))
      .map((k) => k.tone ?? "neutral");
    if (pillarTones.includes("red")) return "unfavorable";
    if (pillarTones.includes("amber")) return "monitor";
    return "favorable";
  }
  const p1 = pillarVerdict("ytd-revenue", "noi");
  const p2 = pillarVerdict("capital-income", "reserve-coverage");
  const p3 = pillarVerdict("working-capital", "ar-current");
  const pillarLine =
    [p1, p2, p3].every((v) => v === "favorable")
      ? "Pillar 1 Operating, Pillar 2 Capital, and Pillar 3 Balance Sheet Stewardship are favorable."
      : [p1, p2, p3].some((v) => v === "unfavorable")
        ? "One or more of Pillar 1 Operating, Pillar 2 Capital, or Pillar 3 Balance Sheet Stewardship is showing unfavourable signals."
        : "Pillars are mostly favorable with specific items to monitor.";

  // 9. Closing action statement.
  const actionLine = anyRed
    ? "Board attention is required this period."
    : anyAmber
      ? "No Board action is required; the items above warrant Committee monitoring."
      : "No Board action is required this period.";

  // Compose. Each clause is its own sentence — board-report cadence.
  const parts: string[] = [opener];
  parts.push(...primaryClauses);
  parts.push(reserveClause);
  if (callout) parts.push(callout);
  if (fbClause) parts.push(fbClause);
  if (partialDataAside) parts.push(partialDataAside);
  parts.push(pillarLine);
  parts.push(actionLine);
  return parts.join(" ");
}

/** Internal: compute variance + amount for a primary metric, with
 *  null-safe handling. */
function computeVariance(input: AccountingMetricInput): {
  variancePct: number | null;
  varianceAmount: number | null;
  actual: number;
  comparator: number | null;
} {
  if (input.comparator === null || input.comparator === 0) {
    return {
      variancePct: null,
      varianceAmount: null,
      actual: input.actual,
      comparator: input.comparator,
    };
  }
  return {
    variancePct: (input.actual - input.comparator) / Math.abs(input.comparator),
    varianceAmount: input.actual - input.comparator,
    actual: input.actual,
    comparator: input.comparator,
  };
}

/** Per-metric prose sentence. Uses board-report cadence: lead with
 *  the actual, follow with the comparator + variance ($ and %). Adds
 *  the word "materially" only when |variance| ≥ 10 %. Returns null
 *  when the comparator is null (skip clause). */
function describePrimaryVariance(args: {
  label: string;
  actual: number;
  comparator: number | null;
}): string | null {
  if (args.comparator === null) return null;
  const variancePct = (args.actual - args.comparator) / Math.abs(args.comparator);
  const absPct = Math.abs(variancePct);
  const varianceAmount = args.actual - args.comparator;
  if (absPct < 0.01) {
    return `${args.label} closed at ${formatMoneyShort(args.actual)}, essentially at the ${formatMoneyShort(args.comparator)} plan.`;
  }
  const direction = variancePct > 0 ? "favorable" : "unfavorable";
  const materialPrefix = absPct >= 0.10 ? "materially " : "";
  return (
    `${args.label} closed at ${formatMoneyShort(args.actual)}, ` +
    `${materialPrefix}${direction} to the ${formatMoneyShort(args.comparator)} plan ` +
    `(${formatVariancePct(variancePct)}, ${formatMoneyShort(Math.abs(varianceAmount))}).`
  );
}

/** Identify the single largest favourable and largest unfavourable
 *  variance across the available primary metrics. Emits a one-
 *  sentence callout. Returns null when nothing material to name
 *  (e.g. all primaries within ±5 % — emit a neutral "no material
 *  variances" line instead of staying silent so the reader knows
 *  the cover was reviewed for them). */
function buildLargestVarianceCallout(
  primaries: Array<{ label: string; variancePct: number | null }>,
): string | null {
  const available = primaries.filter(
    (p): p is { label: string; variancePct: number } => p.variancePct !== null,
  );
  if (available.length === 0) return null;
  // Material threshold for the callout: 5 % (matches the amber
  // band used for KPI tone classification).
  const MATERIAL_THRESHOLD = 0.05;
  const materialFavorable = available
    .filter((p) => p.variancePct >= MATERIAL_THRESHOLD)
    .sort((a, b) => b.variancePct - a.variancePct);
  const materialUnfavorable = available
    .filter((p) => p.variancePct <= -MATERIAL_THRESHOLD)
    .sort((a, b) => a.variancePct - b.variancePct);

  if (materialFavorable.length === 0 && materialUnfavorable.length === 0) {
    return "No primary metric is materially off plan (variance ≥ 5%).";
  }
  const parts: string[] = [];
  if (materialFavorable.length > 0) {
    const top = materialFavorable[0];
    parts.push(
      `The largest favourable variance is ${top.label} (${formatVariancePct(top.variancePct)}).`,
    );
  }
  if (materialUnfavorable.length > 0) {
    const top = materialUnfavorable[0];
    parts.push(
      `The largest unfavourable variance is ${top.label} (${formatVariancePct(top.variancePct)}).`,
    );
  }
  return parts.join(" ");
}

