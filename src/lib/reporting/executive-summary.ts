// Executive Summary — cover-page At-a-Glance KPIs + reactive
// headline narrative.
//
// This service replaces the seven hardcoded React literals that
// previously lived in monthly-package.ts (six KPI cards + the
// headline). Per the Jonas-readiness audit
// (docs/monthly-reporting-data-lineage-audit.md §3 Tier 1, item 1)
// these were the HIGHEST-RISK item in the package — the first
// numbers a board member sees on the cover, which after a Jonas
// import would have continued to read `$14.62M YTD Revenue`,
// `$3.18M NOI`, etc., regardless of real GL data.
//
// Now:
//   • Every KPI value flows from a typed `ExecutiveSummaryInput`.
//   • The headline narrative is generated by `buildExecutiveSummaryHeadline()`
//     — branches on operating, capital, balance-sheet, and AR signals
//     to produce favorable / monitor / unfavorable copy.
//   • Each input carries a `MonthlyAccountingDataSource` tag; the
//     rollup is `dataSource: "live" | "demo"` matching the existing
//     package convention.
//
// The shape of `ExecutiveSummaryOutput` mirrors the existing
// `pkg.executiveSummary` block exactly — same `KpiCard[]`, same
// `headline: string`, same `consideration: BoardConsideration`.
// React on page.tsx renders the result unchanged.

