// ---------------------------------------------------------------------------
// Tone classification per KPI
// ---------------------------------------------------------------------------

/** Standard variance bands for revenue / NOI / capital income.
 *  Inside ±1 % → neutral; favourable up to budget → green; below
 *  budget by 0–5 % → amber; below by ≥ 5 % → red. A `null` or `0`
 *  comparator → neutral (we can't classify against a missing
 *  budget; the headline will note it). */
function toneForBudgetMetric(actual: number, budget: number | null): KpiTone {
  if (budget === null || budget <= 0) return "neutral";
  const variancePct = (actual - budget) / Math.abs(budget);
  if (variancePct >= -0.01) return "green";
  if (variancePct >= -0.05) return "amber";
  return "red";
}

/** Reserve coverage tone — comparator is the policy floor (e.g.
 *  1.25). Above floor → green; within 5 % of floor → amber; below →
 *  red. `null` floor → neutral. */
function toneForReserveCoverage(ratio: number, floor: number | null): KpiTone {
  if (floor === null || floor <= 0) return "neutral";
  if (ratio >= floor) return "green";
  if (ratio >= floor * 0.95) return "amber";
  return "red";
}

/** Working capital tone — same band logic as reserve coverage. */
function toneForWorkingCapital(amount: number, floor: number | null): KpiTone {
  if (floor === null || floor <= 0) return "neutral";
  if (amount >= floor) return "green";
  if (amount >= floor * 0.95) return "amber";
  return "red";
}

/** AR aging tone — drives off the over-90 share crossing the watch
 *  threshold. Below threshold → green; up to 1.5 × threshold →
 *  amber; above 1.5 × threshold → red. */
function toneForArAging(over90Pct: number, watchThreshold: number): KpiTone {
  if (over90Pct < watchThreshold) return "green";
  if (over90Pct < watchThreshold * 1.5) return "amber";
  return "red";
}

// ---------------------------------------------------------------------------
// Pre-format helpers
// ---------------------------------------------------------------------------

function formatPct(fraction: number): string {
  return `${(fraction * 100).toFixed(1)}%`;
}

function formatRatio(ratio: number): string {
  return `${ratio.toFixed(2)}x`;
}

function formatRatioDelta(actual: number, floor: number): string {
  const delta = actual - floor;
  const abs = Math.abs(delta).toFixed(2);
  if (delta > 0) return `${abs}x above floor`;
  if (delta < 0) return `${abs}x below floor`;
  return "at floor";
}

function formatDollarCushion(amount: number, floor: number): string {
  const delta = amount - floor;
  if (delta > 0) return `${formatMoneyShort(delta)} cushion`;
  if (delta < 0) return `${formatMoneyShort(Math.abs(delta))} short of floor`;
  return "at floor";
}

