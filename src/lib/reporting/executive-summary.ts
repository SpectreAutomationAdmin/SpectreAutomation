/**
 * Build the executive summary block from typed input. Pure function;
 * deterministic given inputs. Six KPI cards + reactive headline +
 * consideration cascade.
 */
export function buildExecutiveSummary(
  input: ExecutiveSummaryInput,
): ExecutiveSummaryOutput {
  const kpis: KpiCard[] = [
    buildYtdRevenueCard(input.ytdRevenue),
    buildNoiCard(input.ytdNoiBeforeDepreciation),
    buildCapitalIncomeCard(input.ytdCapitalIncome),
    buildReserveCoverageCard(input.reserveCoverage),
    buildWorkingCapitalCard(input.workingCapital),
    buildArCard(input.arAging),
  ];
  const headline = buildExecutiveSummaryHeadline(input, kpis);
  const consideration = cascadeConsideration(kpis);

  // dataSource rollup — every input carries its own provenance.
  // The block reports `"live"` only when every input is
  // `accounting` or `operational`; any `demo` tag flips it to
  // `"demo"`. `derived` inputs would be unusual here (executive
  // summary inputs are aggregates from accounting/operational
  // services) so we use the shared mapping helper.
  const inputSources: MonthlyAccountingDataSource[] = [
    input.ytdRevenue.dataSource,
    input.ytdNoiBeforeDepreciation.dataSource,
    input.ytdCapitalIncome.dataSource,
    input.reserveCoverage.dataSource,
    input.workingCapital.dataSource,
    input.arAging.dataSource,
  ];
  if (input.fbSubsidy) inputSources.push(input.fbSubsidy.dataSource);
  const dataSource: ReportingDataSource = inputSources.every(
    (s) => toLegacyDataSource(s) === "live",
  )
    ? "live"
    : "demo";

  return { dataSource, kpis, headline, consideration };
}

