/**
 * A single accounting-backed metric with its budget comparator and
 * provenance tag. Future Phase 1 wiring populates these from
 * `getGLAccountTotals()` / `getBalanceSheet()` reads against
 * Jonas-imported journals.
 *
 * `comparator` may be `null` to signal "budget / policy comparator
 * not yet available" (a real condition during partial Jonas
 * imports — actuals may post before the budget snapshot lands). The
 * builder renders an appropriate fallback in the KPI card and the
 * commentary generator omits the corresponding clause.
 */
type AccountingMetricInput = {
  /** Actual YTD value in dollars (or ratio for reserveCoverage; or
   *  fraction 0..1 for AR / F&B percentages). */
  actual: number;
  /** Budget or policy comparator (same units as `actual`). `null`
   *  marks the comparator as not-yet-available. */
  comparator: number | null;
  dataSource: MonthlyAccountingDataSource;
};

/**
 * Optional headline-narrative side-input. The static narrative cited
 * an F&B subsidy line; when the data exists the headline includes
 * that sentence, when it doesn't the headline omits it gracefully.
 */
export type FbSubsidyInput = {
  /** Current F&B subsidy as a fraction of operating dues (0..1). */
  actual: number;
  /** Policy ceiling — typically 0.08. */
  ceiling: number;
  /** Direction of the trailing-12-month trend. */
  trend: "improving" | "stable" | "worsening";
  dataSource: MonthlyAccountingDataSource;
};

/**
 * The typed input to the Executive Summary builder. Phase 1 wiring
 * services produce this shape from prisma reads; the demo input
 * factory (`buildDemoExecutiveSummaryInput`) produces a seeded
 * version for the current package build.
 */
export type ExecutiveSummaryInput = {
  period: ReportingPeriod;
  clubName: string;
  /** Total operating revenue YTD (dollars). */
  ytdRevenue: AccountingMetricInput;
  /** NOI before depreciation YTD (dollars). */
  ytdNoiBeforeDepreciation: AccountingMetricInput;
  /** Capital income YTD (dollars; initiation fees + capital dues +
   *  investment income + transfer-from-ops). */
  ytdCapitalIncome: AccountingMetricInput;
  /** Reserve coverage ratio — reserve balance ÷ 3-year average
   *  capital spend. `actual` is the ratio (e.g. 1.42); `comparator`
   *  is the policy floor (e.g. 1.25). */
  reserveCoverage: AccountingMetricInput;
  /** Working capital — current assets − current liabilities. */
  workingCapital: AccountingMetricInput;
  /** AR aging: `actual` is the current-bucket share (0..1);
   *  `comparator` is the over-90-day share (0..1) — semantically a
   *  watch indicator, not a target. Tone derives from the
   *  watchThreshold below. */
  arAging: AccountingMetricInput & {
    /** Over-90 fraction that triggers amber (typically 0.05). */
    watchThreshold: number;
  };
  /** Optional F&B subsidy line for the headline narrative. */
  fbSubsidy: FbSubsidyInput | null;
};

