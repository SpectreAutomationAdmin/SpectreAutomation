// =============================================================================
// Production entry point — DUAL-READ pattern
// =============================================================================
//
// Mirrors the SoFP + SoA migrations. The Executive Summary block (the
// cover-page At-a-Glance KPIs + reactive headline + board
// consideration) drives off live Reporting Ledger snapshots when
// they exist for the active club, falling back to the demo seed
// otherwise.
//
// LEDGER-DERIVED INPUTS (from Balance Sheet + Income Statement snapshots):
//   • ytdRevenue.actual                ← IS.totalOperatingRevenue
//   • ytdNoiBeforeDepreciation.actual  ← IS.noiBeforeDepreciation
//   • ytdCapitalIncome.actual          ← IS.totalCapitalIncome
//   • workingCapital.actual            ← BS  (current-asset sum − current-liability sum)
//
// AUXILIARY INPUTS (typed; awaiting their own ledger services):
//   • Budget comparators for all four monetary KPIs (await Budget importer)
//   • reserveCoverage.actual + comparator (await Reserve Study projection)
//   • workingCapital.comparator policy floor (await policy-table importer)
//   • arAging.* (await AR Aging projection)
//   • fbSubsidy.* (await F&B subledger aggregate)
//
// When any auxiliary input is missing, the corresponding KPI card
// renders a "Pending" comparator and tones neutral — the existing
// builder handles this gracefully (see PENDING_COMPARATOR_ROW above).

/**
 * Auxiliary inputs the Executive Summary needs from sources outside
 * the BS + IS snapshots. Each typed entry will move to its own
 * ledger projection in Phase 3.
 */
export type ExecutiveSummaryAuxiliaryInputs = {
  /** Budget comparators per KPI (null when not yet available). */
  budget: {
    ytdRevenue: number | null;
    ytdNoiBeforeDepreciation: number | null;
    ytdCapitalIncome: number | null;
    /** Working-capital policy floor (dollars). */
    workingCapitalFloor: number | null;
  };
  /** Reserve coverage — `actual` is the ratio (reserve balance ÷
   *  3-year average capital spend); `comparator` is the policy
   *  floor. Awaiting Reserve Study projection. */
  reserveCoverage: {
    actual: number | null;
    floor: number | null;
  };
  /** AR aging block. `actual` is the current-bucket share (0..1);
   *  `over90Pct` is the over-90 share; `watchThreshold` is the
   *  amber trigger. Awaiting AR Aging projection. */
  arAging: {
    actualCurrentPct: number | null;
    over90Pct: number | null;
    watchThreshold: number;
  };
  /** F&B subsidy — optional. Drives a sentence in the headline
   *  narrative. Awaiting F&B subledger aggregate. */
  fbSubsidy: FbSubsidyInput | null;
};

/**
 * Build an `ExecutiveSummaryInput` from BS + IS snapshots plus the
 * auxiliary inputs. Pure function; same inputs → same output.
 */
export function buildExecutiveSummaryInputFromSnapshots(args: {
  period: ReportingPeriod;
  clubName: string;
  ytdIncomeStatement: IncomeStatementSnapshot;
  balanceSheet: BalanceSheetSnapshot;
  auxiliaryInputs: ExecutiveSummaryAuxiliaryInputs;
}): ExecutiveSummaryInput {
  const { ytdIncomeStatement: is, balanceSheet: bs, auxiliaryInputs: aux } = args;

  // Working capital from BS lines (current-asset − current-liability).
  let currentAssets = 0;
  let currentLiabilities = 0;
  for (const l of bs.lines) {
    if (l.category === "current-asset") currentAssets += l.amount;
    else if (l.category === "current-liability") currentLiabilities += l.amount;
  }
  const workingCapital = currentAssets - currentLiabilities;

  // Provenance: tag accounting-derived inputs `accounting`, derived
  // (BS) as `derived`, others as `demo`/`operational` per their
  // upstream source.
  const accountingTag: MonthlyAccountingDataSource =
    is.dataSource === "demo" ? "demo" : "accounting";
  const derivedTag: MonthlyAccountingDataSource =
    bs.dataSource === "demo" ? "demo" : "derived";

  return {
    period: args.period,
    clubName: args.clubName,
    ytdRevenue: {
      actual: is.totalOperatingRevenue,
      comparator: aux.budget.ytdRevenue,
      dataSource: accountingTag,
    },
    ytdNoiBeforeDepreciation: {
      actual: is.noiBeforeDepreciation,
      comparator: aux.budget.ytdNoiBeforeDepreciation,
      dataSource: accountingTag,
    },
    ytdCapitalIncome: {
      actual: is.totalCapitalIncome,
      comparator: aux.budget.ytdCapitalIncome,
      dataSource: accountingTag,
    },
    reserveCoverage: {
      actual: aux.reserveCoverage.actual ?? 0,
      comparator: aux.reserveCoverage.floor,
      dataSource: aux.reserveCoverage.actual === null ? "demo" : "derived",
    },
    workingCapital: {
      actual: workingCapital,
      comparator: aux.budget.workingCapitalFloor,
      dataSource: derivedTag,
    },
    arAging: {
      actual: aux.arAging.actualCurrentPct ?? 0,
      comparator: aux.arAging.over90Pct ?? 0,
      watchThreshold: aux.arAging.watchThreshold,
      dataSource: aux.arAging.actualCurrentPct === null ? "demo" : "operational",
    },
    fbSubsidy: aux.fbSubsidy,
  };
}

/**
 * Production dual-read entry point. Resolves BS + YTD IS snapshots
 * from the ledger (self-healing projection from a TB when needed)
 * and builds the Executive Summary from them. Falls back to the
 * demo seed when no ledger data exists.
 */
export async function getExecutiveSummaryForClub(args: {
  clubId: string;
  clubName: string;
  period: ReportingPeriod;
  ledger: ReportingLedger & ReportingLedgerWriter;
  auxiliaryInputs: ExecutiveSummaryAuxiliaryInputs;
  demoFallback?: () => ExecutiveSummaryOutput;
}): Promise<ExecutiveSummaryOutput> {
  const snapshots = await resolveSnapshotsForExecutiveSummary({
    ledger: args.ledger,
    clubId: args.clubId,
    period: args.period,
  });

  if (snapshots) {
    return buildExecutiveSummary(
      buildExecutiveSummaryInputFromSnapshots({
        period: args.period,
        clubName: args.clubName,
        ytdIncomeStatement: snapshots.is,
        balanceSheet: snapshots.bs,
        auxiliaryInputs: args.auxiliaryInputs,
      }),
    );
  }

  if (args.demoFallback) return args.demoFallback();
  return buildDemoExecutiveSummary({
    period: args.period,
    clubName: args.clubName,
  });
}

// ---------------------------------------------------------------------------
// Snapshot resolver — self-healing (projects from TB on demand)
// ---------------------------------------------------------------------------

async function resolveSnapshotsForExecutiveSummary(args: {
  ledger: ReportingLedger & ReportingLedgerWriter;
  clubId: string;
  period: ReportingPeriod;
}): Promise<{ bs: BalanceSheetSnapshot; is: IncomeStatementSnapshot } | null> {
  const asOf = endOfDayUtc(args.period.periodEnd);
  const tb = await args.ledger.getTrialBalance(args.clubId, asOf);
  if (!tb) return null;

  // Founder rule 2026-07-01 v14.12 — direct snapshot preference.
  // v14.13 refinement — YTD Revenue means fiscal-year-start to
  // period-end, NOT month-start to period-end. Read the TB
  // snapshot's `periodStart` (populated by v14.11 synth to the
  // covering fiscal year start) so the IS query returns the full
  // YTD window even for mid-year periods.
  const directBs = await args.ledger.getBalanceSheet(args.clubId, asOf);
  const directIs = await args.ledger.getIncomeStatement(
    args.clubId,
    tb.periodStart,
    asOf,
  );
  if (directBs && directIs) {
    return { bs: directBs, is: directIs };
  }

  // BS projection — idempotent via payload hash; no-op write when TB
  // hasn't changed.
  const bsProj = new BalanceSheetProjection({
    ledger: args.ledger,
    writer: args.ledger,
  });
  const bsResult = await bsProj.getBalanceSheetSnapshot({
    clubId: args.clubId,
    asOf,
  });

  // IS projection — YTD mode.
  const isProj = new IncomeStatementProjection({
    ledger: args.ledger,
    writer: args.ledger,
  });
  const isResult = await isProj.getIncomeStatementSnapshot({
    clubId: args.clubId,
    periodStart: args.period.periodStart,
    periodEnd: asOf,
    fiscalYearLabel: tb.fiscalYearLabel,
    fiscalPeriodSequence: tb.fiscalPeriodSequence,
    mode: "ytd",
  });

  if (bsResult.status !== "succeeded" || isResult.status !== "succeeded") {
    return null;
  }
  return { bs: bsResult.snapshot, is: isResult.snapshot };
}

function endOfDayUtc(d: Date): Date {
  return new Date(
    Date.UTC(
      d.getUTCFullYear(),
      d.getUTCMonth(),
      d.getUTCDate(),
      23, 59, 59, 999,
    ),
  );
}

