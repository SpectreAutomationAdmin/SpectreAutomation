// Food & Beverage Statistics service — chapter XIII (Operations &
// Analytics group). Owns 4 KPI cards + 4 chart datasets (Monthly F&B
// Revenue vs. Cost, Revenue by Category donut, Monthly Cover Counts
// vs Budget vs Prior Year, Food Cost % by Month line chart) + two
// reactive chart callouts.
//
// All period labels flow from `ReportingPeriod` per the Reporting
// Period Golden Rule. The seeded monthly arrays carry 12 entries
// (Jan–Dec) and the service SLICES to the right number of months
// based on `period.month` — so a May 2026 report shows 5 monthly
// bars, a March report shows 3, and so on. Future integration with
// live POS / accounting data replaces the seed without touching React.

import type { ReportingDataSource } from "@/lib/reporting/monthly-package";
import type { ReportingPeriod } from "@/lib/reporting/reporting-period";

// =============================================================================
// Public types
// =============================================================================

export type FbKpiTreatment = "primary" | "favorable" | "neutral" | "watch";
export type FbTone = "favorable" | "risk" | "neutral";

export type FbKpiCard = {
  key: string;
  /** Pre-formatted hero value (e.g. "$2.486M", "37.8%", "31,800"). */
  valueLabel: string;
  /** Uppercase label (e.g. "Total F&B Revenue YTD"). */
  label: string;
  /** Optional sub-line below the label. */
  subLabel?: string;
  treatment: FbKpiTreatment;
};

export type FbMonthlyPoint = {
  /** Pre-formatted month name (e.g. "January"). */
  monthLabel: string;
  /** Index in the calendar year, 1-indexed. Useful for ordering. */
  monthNumber: number;
  /** Revenue in raw dollars (not thousands) for tooltip math. */
  revenue: number;
  /** Cost in raw dollars. */
  cost: number;
  /** Pre-computed cost % of revenue (0..100). */
  costPct: number;
  /** Cover counts. */
  coversActual: number;
  coversBudget: number;
  coversPriorYear: number;
};

export type FbCategorySlice = {
  key: string;
  label: string;
  amount: number;
  share: number;
  fillHex: string;
};

export type FbChartCallout = {
  /** Pre-formatted narrative — generated by the service from the
   *  observed swings + the budget target. */
  text: string;
};

export type FoodBeverageStatistics = {
  dataSource: ReportingDataSource;
  // Header chrome — mirrors the other Saguaro chapters.
  eyebrow: string;
  title: string;
  periodLabel: string;
  introNote: string;
  statementNumber: string;
  documentChip: string;
  preparedFor: string;
  // 4 primary KPI cards.
  kpiCards: ReadonlyArray<FbKpiCard>;
  /**
   * 4 secondary KPI cards rendered as the second row directly
   * beneath the primary row. Column alignment is deliberate per
   * the F&B Committee's KPI taxonomy:
   *
   *    Top Row              ↓        Bottom Row
   *    ─────────────────────────────────────────────────
   *    Total F&B Revenue    →   Revenue per Server
   *    F&B Cost %           →   Member Satisfaction
   *    Total Covers         →   Average Check
   *    F&B Gross Margin     →   Monthly Gratuities
   *
   * Average Check sits directly under Total Covers because the
   * two metrics share their per-cover denominator.
   */
  secondaryKpiCards: ReadonlyArray<FbKpiCard>;
  // Chart datasets — single source of truth for all 4 charts.
  charts: {
    /** Monthly Revenue vs Cost grouped bars. */
    monthlyRevenueCost: ReadonlyArray<FbMonthlyPoint>;
    /** Revenue by category donut (5 slices). Shares sum to 1.0. */
    revenueByCategory: ReadonlyArray<FbCategorySlice>;
    /** Monthly Cover Counts: Actual / Budget / Prior Year grouped bars. */
    monthlyCoverCounts: ReadonlyArray<FbMonthlyPoint>;
    /** Food Cost % by Month line series + the budget target line. */
    foodCostTrend: {
      points: ReadonlyArray<{ monthLabel: string; monthNumber: number; costPct: number }>;
      budgetTargetPct: number;
    };
    /** Pre-formatted chart subtitles (period-aware). */
    subtitles: {
      monthlyRevenueCost: string;
      revenueByCategory: string;
      monthlyCoverCounts: string;
      foodCostTrend: string;
    };
    /** Founder rule 2026-07-05 v15.10 — chip labels for the
     *  dark-green editorial header's top-right gold pill,
     *  matching the Payroll Analysis chapter (v15.8). */
    chipLabels: {
      monthlyRevenueCost: string;
      revenueByCategory: string;
      monthlyCoverCounts: string;
      foodCostTrend: string;
    };
    /** Founder rule 2026-07-05 v15.10 — one executive commentary
     *  per chart, generated dynamically from the report data.
     *  Every callout is rendered beneath its chart in the
     *  Stewardship-style green-wash panel. */
    callouts: {
      monthlyRevenueCost: FbChartCallout;
      revenueByCategory:  FbChartCallout;
      monthlyCoverCounts: FbChartCallout;
      foodCostTrend:      FbChartCallout;
    };
  };
};

