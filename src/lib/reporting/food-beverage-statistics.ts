// =============================================================================
// Formatters
// =============================================================================

function formatMillions(value: number): string {
  if (value === 0) return "—";
  return `$${(value / 1_000_000).toFixed(3)}M`;
}

function formatThousandsOneDecimal(value: number): string {
  if (value === 0) return "—";
  const sign = value < 0 ? "-" : "";
  return `${sign}$${(Math.abs(value) / 1_000).toFixed(1)}K`;
}

function formatThousands(value: number): string {
  if (value === 0) return "—";
  const sign = value < 0 ? "-" : "";
  return `${sign}$${Math.round(Math.abs(value) / 1_000).toLocaleString("en-US")}K`;
}

function formatInteger(value: number): string {
  return Math.round(value).toLocaleString("en-US");
}

function formatPercent1(value: number): string {
  return `${value.toFixed(1)}%`;
}

function formatCurrencyCents(value: number): string {
  return `$${value.toFixed(2)}`;
}

